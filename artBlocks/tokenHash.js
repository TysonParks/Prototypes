// MARK: Hash Generation from https://github.com/ArtBlocks/artblocks-docs
function random_hash() {
  let x = "0123456789abcdef", hash = '0x'
  for (let i = 64; i > 0; --i) {
    hash += x[Math.floor(Math.random() * x.length)]
  }
  return hash
}

